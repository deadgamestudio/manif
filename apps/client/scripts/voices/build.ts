// The cameos' voice clips (#137): public/voices/<cameo>/<kind>-<index>.mp3,
// and their lengths in packages/shared/src/cameo/clips.ts (the server keeps
// each bubble up as long as its clip).
//
//   bun run voices                 # re-measure the clips already in public/voices
//   bun run voices <raw-folder>    # first encode the raw takes, then measure
//
// A raw take is named `<cameo>-<kind>-<index>.mp3` (e.g. moluchan-rally-2.mp3).
// A line whose text repeats an earlier line of the same cameo may have no raw
// take of its own: it gets a copy of that earlier one. Encoding trims the
// silence at both ends, evens out the loudness and makes a small mono MP3
// (Safari and iOS play it).
//
// To swap a voice for a real recording: drop a file of the same name in
// public/voices/<cameo>/ (or a raw take in a folder and pass it), then run this
// again so the lengths follow. Needs ffmpeg and ffprobe on the PATH.

import { spawnSync } from "node:child_process";
import { copyFileSync, existsSync, mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { CAMEO_VOICE_LINES, cameoClipPath } from "@manif/shared";

const CLIENT = join(import.meta.dir, "../..");
const PUBLIC = join(CLIENT, "public");
const TABLE = join(CLIENT, "../../packages/shared/src/cameo/clips.ts");

/** Quieter than this counts as silence at the ends. */
const SILENCE = "-45dB";
const TRIM = [
  `silenceremove=start_periods=1:start_threshold=${SILENCE}:start_silence=0.04`,
  "areverse",
  `silenceremove=start_periods=1:start_threshold=${SILENCE}:start_silence=0.08`,
  "areverse",
  // A few milliseconds of fade so the cut ends don't click.
  "afade=t=in:d=0.01",
  // Every voice about as loud as the others, whoever recorded it.
  "loudnorm=I=-18:TP=-2:LRA=11",
].join(",");

function run(cmd: string, args: string[]): string {
  const r = spawnSync(cmd, args, { encoding: "utf8" });
  if (r.status !== 0) throw new Error(`${cmd} ${args.join(" ")}\n${r.stderr}`);
  return r.stdout;
}

function encode(raw: string, out: string) {
  mkdirSync(join(out, ".."), { recursive: true });
  run("ffmpeg", ["-y", "-v", "error", "-i", raw, "-af", TRIM, "-ac", "1", "-ar", "32000", "-c:a", "libmp3lame", "-b:a", "48k", "-map_metadata", "-1", out]);
}

function seconds(file: string): number {
  const out = run("ffprobe", ["-v", "error", "-show_entries", "format=duration", "-of", "default=nw=1:nk=1", file]);
  return Math.round(Number(out.trim()) * 100) / 100;
}

const rawDir = process.argv[2];
const table: Record<string, number[]> = {};
const missing: string[] = [];
for (const [cameo, lines] of Object.entries(CAMEO_VOICE_LINES)) {
  table[cameo] = lines.map((line, i) => {
    const path = cameoClipPath(cameo, i);
    if (!path) throw new Error(`${cameo} ${i}: no path`);
    const file = join(PUBLIC, path);
    if (rawDir) {
      const raw = join(rawDir, `${cameo}-${line.kind}-${i}.mp3`);
      const same = lines.findIndex((l) => l.text === line.text);
      if (existsSync(raw)) encode(raw, file);
      else if (same < i) {
        const first = cameoClipPath(cameo, same);
        if (first && existsSync(join(PUBLIC, first))) copyFileSync(join(PUBLIC, first), file);
      }
    }
    if (!existsSync(file)) {
      missing.push(path);
      return 0;
    }
    return seconds(file);
  });
}

const body = Object.entries(table)
  .map(([cameo, list]) => `  ${cameo}: [${list.join(", ")}],`)
  .join("\n");
writeFileSync(
  TABLE,
  `// Generated by apps/client/scripts/voices/build.ts (bun run voices): do not edit by hand.
// How long each cameo line's voice clip lasts, in seconds, by line index (0: no clip).

export const CAMEO_CLIP_SECONDS: Readonly<Record<string, readonly number[]>> = {
${body}
};
`,
);
console.log(`clips.ts written. ${missing.length ? `Missing: ${missing.join(", ")}` : "Every line has a clip."}`);
